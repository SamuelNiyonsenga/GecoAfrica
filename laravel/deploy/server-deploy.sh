#!/usr/bin/env bash
# Deploys the GECO Africa Laravel site on the cPanel server from GitHub.
# Run it in cPanel → Terminal. See DEPLOY.md, section 11.
#
#   First time only (downloads the repo; changes nothing on the site):
#     git clone --depth 1 --filter=blob:none --sparse https://github.com/SamuelNiyonsenga/GecoAfrica.git ~/geco-repo
#     git -C ~/geco-repo sparse-checkout set laravel
#
#   Every deploy, after merging to main:
#     bash ~/geco-repo/laravel/deploy/server-deploy.sh            # preview: lists changes, changes nothing
#     bash ~/geco-repo/laravel/deploy/server-deploy.sh --apply    # backs up code + database, then deploys
#
# Only ~/new.gecoafrica.com (the folder gecoafrica.com serves from) and the site's own
# database are touched. Other sites on this cPanel account are never read or changed.
# Uses PHP 8.2 by full path: plain `php` in this server's Terminal is 7.2.

set -euo pipefail

# ---------------------------------------------------------------- settings
SITE="${SITE:-$HOME/new.gecoafrica.com}"                 # live Laravel app (gecoafrica.com)
REPO="${REPO:-$HOME/geco-repo}"                          # clone of the GitHub repo (only laravel/ is checked out)
BACKUPS="${BACKUPS:-$HOME/geco-backups}"                    # code + database backups, newest 5 kept
REPO_URL="https://github.com/SamuelNiyonsenga/GecoAfrica.git"
BRANCH="main"
PHP="${PHP:-/opt/alt/php82/usr/bin/php}"                # plain `php` in Terminal is 7.2 on this server
KEEP_BACKUPS=5

# Files that live only on the server and must never be overwritten or removed.
EXCLUDES=(
  --exclude='/.env' --exclude='/.env.*'
  --exclude='/.htaccess' --exclude='/.htaccess-old' --exclude='/php.ini*' --exclude='/.user.ini'
  --exclude='/cgi-bin/' --exclude='/error_log' --exclude='/public/error_log'
  --exclude='/storage/' --exclude='/vendor/' --exclude='/node_modules/'
  --exclude='/public/storage' --exclude='/public/v.php' --exclude='/public/.well-known/'
  --exclude='/bootstrap/cache/*.php'
  --exclude='/deploy/build/' --exclude='/deploy/*.zip' --exclude='/tests/'
)

# Files removed from the repo that must also go from the server (rsync never deletes on its own).
REMOVED_FILES=(
  "public/robots.txt"    # Nov 2026: robots.txt is now generated by the site
)

say()  { printf '\n\033[1m==> %s\033[0m\n' "$*"; }
fail() { printf '\n\033[31mSTOPPED: %s\033[0m\n' "$*" >&2; exit 1; }

# ---------------------------------------------------------------- checks
[ -x "$PHP" ] || fail "PHP 8.2 not found at $PHP"
command -v rsync >/dev/null || fail "rsync is not installed on this server."
command -v git >/dev/null || fail "git is not installed on this server."
"$PHP" -r 'exit(version_compare(PHP_VERSION, "8.2.0", ">=") ? 0 : 1);' || fail "$PHP is not PHP 8.2+"

if [ "${1:-}" = "setup" ]; then
  say "Downloading the repository to $REPO (only the laravel/ folder)"
  [ -d "$REPO/.git" ] && fail "$REPO already exists. Nothing to set up."
  git clone --depth 1 --filter=blob:none --sparse --branch "$BRANCH" "$REPO_URL" "$REPO"
  git -C "$REPO" sparse-checkout set laravel
  say "Done. Nothing on the website was changed. Next, preview a deploy:"
  echo "    bash $REPO/laravel/deploy/server-deploy.sh"
  exit 0
fi

APPLY=false
[ "${1:-}" = "--apply" ] && APPLY=true

[ -d "$REPO/.git" ] || fail "Download the repo first (see the top of this file)."
[ -f "$SITE/artisan" ] && [ -f "$SITE/.env" ] || fail "$SITE does not look like the live Laravel site."
SRC="$REPO/laravel"
artisan() { (cd "$SITE" && "$PHP" artisan "$@"); }

say "Getting the latest code from GitHub ($BRANCH)"
git -C "$REPO" fetch --depth 1 origin "$BRANCH"
git -C "$REPO" reset --hard "origin/$BRANCH"
git -C "$REPO" log -1 --format='    %h  %ad  %s' --date=short

# ---------------------------------------------------------------- preview
if ! $APPLY; then
  say "PREVIEW ONLY: these files would be added or updated on the live site"
  rsync -rlptci --dry-run "${EXCLUDES[@]}" "$SRC/" "$SITE/" | grep -v '^\.d' || echo "    (no file changes)"
  for file in "${REMOVED_FILES[@]}"; do
    if [ -e "$SITE/$file" ]; then echo "    would delete: $file"; fi
  done
  cmp -s "$SRC/composer.lock" "$SITE/composer.lock" || echo "    composer.lock changed: packages would be updated"
  say "Nothing was changed. To deploy for real:"
  echo "    bash $SRC/deploy/server-deploy.sh --apply"
  exit 0
fi

# ---------------------------------------------------------------- backup
STAMP="$(date +%Y%m%d-%H%M%S)"
mkdir -p "$BACKUPS"
say "Backing up the site code to $BACKUPS/code-$STAMP.tar.gz (uploads and vendor are not touched, so not included)"
tar -czf "$BACKUPS/code-$STAMP.tar.gz" -C "$(dirname "$SITE")" \
  --exclude="$(basename "$SITE")/vendor" --exclude="$(basename "$SITE")/storage" "$(basename "$SITE")"

say "Backing up the database to $BACKUPS/db-$STAMP.sql.gz"
env_value() { grep -E "^$1=" "$SITE/.env" | tail -1 | cut -d= -f2- | sed -e 's/^"//' -e 's/"$//' -e "s/^'//" -e "s/'$//"; }
DB_NAME="$(env_value DB_DATABASE)"; DB_USER="$(env_value DB_USERNAME)"; DB_HOST="$(env_value DB_HOST)"
MYSQL_PWD="$(env_value DB_PASSWORD)" mysqldump --single-transaction --no-tablespaces \
  -h "${DB_HOST:-localhost}" -u "$DB_USER" "$DB_NAME" | gzip > "$BACKUPS/db-$STAMP.sql.gz" \
  || fail "Database backup failed, so nothing was deployed."
chmod 600 "$BACKUPS"/*
ls -1t "$BACKUPS"/code-*.tar.gz 2>/dev/null | tail -n +$((KEEP_BACKUPS + 1)) | xargs -r rm -f
ls -1t "$BACKUPS"/db-*.sql.gz 2>/dev/null | tail -n +$((KEEP_BACKUPS + 1)) | xargs -r rm -f

# ---------------------------------------------------------------- deploy
say "Showing a maintenance page while the update runs"
artisan down --retry=30 || true
trap 'echo; echo "Something failed. Bringing the site back up."; (cd "$SITE" && "$PHP" artisan up) || true' ERR

LOCK_CHANGED=false
cmp -s "$SRC/composer.lock" "$SITE/composer.lock" || LOCK_CHANGED=true

say "Copying the new code into $SITE"
rsync -rlptc "${EXCLUDES[@]}" "$SRC/" "$SITE/"
for file in "${REMOVED_FILES[@]}"; do
  if [ -e "$SITE/$file" ]; then rm -f "$SITE/$file"; echo "    deleted: $file"; fi
done

if $LOCK_CHANGED; then
  say "Packages changed: running composer install with PHP 8.2"
  COMPOSER_BIN="$(readlink -f "$(command -v composer)")"
  (cd "$SITE" && "$PHP" "$COMPOSER_BIN" install --no-dev --optimize-autoloader --no-interaction --no-progress)
fi

say "Updating the database"
artisan migrate --force

say "Refreshing caches"
artisan optimize:clear
artisan optimize
[ -e "$SITE/public/storage" ] || artisan storage:link

artisan up
trap - ERR
say "Deployed. Open https://gecoafrica.com to check. Backups are in $BACKUPS"
